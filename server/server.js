function bearingBetween(from, to) {
  const dLon = ((to.lng - from.lng) * Math.PI) / 180;
  const lat1 = (from.lat * Math.PI) / 180;
  const lat2 = (to.lat * Math.PI) / 180;
  const y = Math.sin(dLon) * Math.cos(lat2);
  const x =
    Math.cos(lat1) * Math.sin(lat2) -
    Math.sin(lat1) * Math.cos(lat2) * Math.cos(dLon);
  return ((Math.atan2(y, x) * 180) / Math.PI + 360) % 360;
}

async function fetchAllStationStopTimes() {
  return Promise.all(
    EXPO_STATIONS.map(async (station) => {
      try {
        const resolvedStopId = resolveStopId(station);
        const data = await fetchStoptimes(resolvedStopId, 60);
        return { station, resolvedStopId, stopTimes: data.stopTimes || [] };
      } catch (e) {
        console.error(`train fetch ${station.id}:`, e.message);
        return { station, resolvedStopId: null, stopTimes: [] };
      }
    })
  );
}

function buildTrips(perStation) {
  const trips = new Map();
  
  for (const { station, resolvedStopId, stopTimes } of perStation) {
    if (!resolvedStopId) continue;
    
    for (const st of stopTimes) {
      const place = st.place || {};
      if (!isAtQueriedStation(place, resolvedStopId)) continue;
      if (!isExpoRoute(st)) continue;
      
      const tripId = st.tripId;
      if (!tripId) continue;
      
      const depIso = place.departure || place.scheduledDeparture;
      if (!depIso) continue;
      const t = Date.parse(depIso);
      if (!Number.isFinite(t)) continue;

      if (!trips.has(tripId)) trips.set(tripId, []);
      
      const tripStops = trips.get(tripId);
    
      // If this trip already has a record for this station, skip it.
      if (!tripStops.some(s => s.stationId === station.id)) {
        tripStops.push({
          stationId: station.id,
          lat: station.lat,
          lng: station.lng,
          time: t,
          headsign: st.headsign || null,
        });
      }
    }
  }
  
  for (const stops of trips.values()) stops.sort((a, b) => a.time - b.time);
  return trips;
}

function interpolateTrains(trips, nowMs) {
  const trains = [];
  const LOOKAHEAD_MS = 30000;

  for (const [tripId, stops] of trips) {
    // Allow trips with only 1 stop (e.g. arriving at terminus)
    if (stops.length === 0) continue;

    let segment = null;
    let status = 'IN_TRANSIT';
    let currentPos = null;
    let nextPos = null;
    let currentStation = null;
    let nextStation = null;
    let minutesToNext = 0;

    // 1. Find where the train is right now
    for (let i = 0; i < stops.length - 1; i++) {
      const a = stops[i];
      const b = stops[i + 1];
      if (a.time <= nowMs && nowMs <= b.time) {
        segment = { a, b };
        break;
      }
    }

    if (segment) {
      // Train is moving between two stations
      const { a, b } = segment;
      const span = b.time - a.time;
      const frac = (nowMs - a.time) / span;
      
      currentPos = {
        lat: a.lat + (b.lat - a.lat) * frac,
        lng: a.lng + (b.lng - a.lng) * frac
      };
      currentStation = a.stationId;
      nextStation = b.stationId;
      minutesToNext = Math.max(0, Math.round((b.time - nowMs) / 60000));

      // 30-second lookahead for smooth animation
      const futureTime = nowMs + LOOKAHEAD_MS;
      if (futureTime < b.time) {
        const futureFrac = (futureTime - a.time) / span;
        nextPos = {
          lat: a.lat + (b.lat - a.lat) * futureFrac,
          lng: a.lng + (b.lng - a.lng) * futureFrac
        };
      } else {
        nextPos = { lat: b.lat, lng: b.lng }; // Arrives at next station
      }
    } else {
      // Train is sitting at a station (either just arrived, or hasn't departed yet)
      const firstFutureStop = stops.find(s => s.time > nowMs);
      const lastPastStop = [...stops].reverse().find(s => s.time <= nowMs);
      
      if (!firstFutureStop && !lastPastStop) continue;

      const station = lastPastStop || firstFutureStop;
      currentPos = { lat: station.lat, lng: station.lng };
      nextPos = { lat: station.lat, lng: station.lng };
      
      currentStation = station.stationId;
      nextStation = firstFutureStop ? firstFutureStop.stationId : station.stationId;
      minutesToNext = firstFutureStop ? Math.max(0, Math.round((firstFutureStop.time - nowMs) / 60000)) : 0;
      
      status = 'AT_STATION';
    }

    const headsign = (stops[0].headsign || '').replace(/^Expo\s+Line\s+/i, '').trim();

    trains.push({
      tripId,
      lat: currentPos.lat,
      lng: currentPos.lng,
      nextLat: nextPos.lat,
      nextLng: nextPos.lng,
      status: status, // <-- Frontend uses this for color
      headsign: headsign || null,
      fromStation: currentStation,
      toStation: nextStation,
      minutesToNext,
      // Required for frontend bearing calculation
      fromLat: currentPos.lat,
      fromLng: currentPos.lng,
      toLat: nextPos.lat,
      toLng: nextPos.lng,
    });
  }
  return trains;
}

